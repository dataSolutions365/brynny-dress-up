// Builds 3d/game.js from the files in 3d/src.
//
// The 3D world is written as small files in 3d/src, one per feature (a place, the avatar, the bakery...).
// They all share one set of variables, so this script joins them, in file-name order, into 3d/game.js,
// which is what 3d/index.html loads. No install needed, just Node:
//
//   node 3d/build.mjs           rebuild 3d/game.js after changing anything in 3d/src
//   node 3d/build.mjs --check   fail if 3d/game.js is out of date (GitHub runs this on pull requests)
//
// Never edit 3d/game.js by hand. To add a new feature file, give it a number so it lands in the
// right order, for example 21b-ice-rink.js runs after 21-bakery.js.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, 'src');
const outFile = path.join(here, 'game.js');

const files = fs.readdirSync(srcDir).filter(f => f.endsWith('.js')).sort();
let out = '// GENERATED by 3d/build.mjs from the files in 3d/src. Do not edit this file; edit 3d/src and run: node 3d/build.mjs\n';
for (const f of files) {
  let body = fs.readFileSync(path.join(srcDir, f), 'utf8');
  if (!body.endsWith('\n')) body += '\n';
  out += `// ---- src/${f} ----\n` + body;
}

if (process.argv.includes('--check')) {
  const now = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (now !== out) {
    console.error('3d/game.js is out of date. Run: node 3d/build.mjs and commit the result.');
    process.exit(1);
  }
  console.log(`3d/game.js is up to date (${files.length} files).`);
} else {
  fs.writeFileSync(outFile, out);
  console.log(`Built 3d/game.js from ${files.length} files.`);
}
